# gen_mood_frames.py - fits the new mood art (happy x4, hungry teen/adult) into each stage's sprite box,
# matched to that stage's idle frame (same height + same feet line). Writes mood_frames.h + mood_preview.png.
# usage: python3 gen_mood_frames.py [threshold=190]   (run in the folder holding the PNGs + new/)
# The new art lives in tools/mood_art/: copy it into new/ (and child_idle_look_around.png next to the pack PNGs).
from PIL import Image, ImageDraw
import numpy as np, sys
T=int(sys.argv[1]) if len(sys.argv)>1 else 190
# stage, box w,h, idle png, union-crop pngs (same list gen_frames.py used), new frames
# per stage: box w,h, idle png, union-crop list (same as gen_frames.py), then the 4 moods in order
# sad, calm, happy, love. ('old', png) = existing pack art (already in pet_frames.h or cropped the same way),
# ('new', png) = newly drawn art fitted to the idle's height + feet line.
MOODS=['sad','calm','happy','love']
STAGES=[
 ('baby',55,56,'idle',['idle','idle_blink','idle_ear_twitch','idle_hungry','idle_tired','feed','pet','play'],
  [('old','idle_hungry'),('old','idle_look_around'),('new','new/idle_happy'),('new','new/idle_love')]),
 ('kid',66,68,'child_idle',['child_idle','child_idle_blink','child_idle_ear_twitch','child_idle_hungry','child_idle_tired','child_feed','child_pet','child_play'],
  [('old','child_idle_hungry'),('old','child_idle_look_around'),('new','new/child_idle_happy'),('new','new/child_idle_love')]),
 ('teen',59,80,'youth_active_idle',['youth_active_idle','youth_active_signature','youth_active_feed','youth_active_pet','youth_active_play'],
  [('new','new/youth_active_hungry'),('old','youth_active_signature'),('new','new/youth_active_happy'),('new','new/youth_active_love')]),
 ('adult',100,96,'adult_active_idle',['adult_active_idle','adult_active_signature','adult_active_feed','adult_active_pet','adult_active_play'],
  [('new','new/adult_active_hungry'),('old','adult_active_signature'),('new','new/adult_active_happy'),('new','new/adult_active_love')]),
]
def outside(a):
    im=Image.fromarray(a.astype('uint8')).copy(); w,h=im.size
    for s in [(0,0),(w-1,0),(0,h-1),(w-1,h-1)]:
        if im.getpixel(s)==255: ImageDraw.floodfill(im,s,128)
    return np.array(im)==128
def pack(b):
    h,w=b.shape; rb=(w+7)//8; out=[]
    for y in range(h):
        for bx in range(rb):
            v=0
            for i in range(8):
                x=bx*8+i
                if x<w and b[y,x]: v|=0x80>>i
            out.append(v)
    return out
def arr(name,data):
    s=f'const uint8_t {name}[] PROGMEM = {{\n'
    for i in range(0,len(data),16): s+='  '+','.join(f'0x{v:02X}' for v in data[i:i+16])+',\n'
    return s+'};\n'
def bbox(b):
    ys,xs=np.where(b); return xs.min(),xs.max()+1,ys.min(),ys.max()+1
def old_frame(png,union,W,H):
    ims=[np.array(Image.open(n+'.png').convert('L')) for n in union]
    ink=np.zeros(ims[0].shape,bool)
    for i in ims: ink|=i<128
    x0,x1,y0,y1=bbox(ink); p=2; H0,W0=ink.shape
    x0,x1,y0,y1=max(x0-p,0),min(x1+p,W0),max(y0-p,0),min(y1+p,H0)
    src=Image.open(png+'.png').convert('L').crop((x0,y0,x1,y1))
    L=np.array(src.resize((W,H),Image.BOX))<T
    o=outside(np.where(np.array(src)<128,0,255))
    M=(np.array(Image.fromarray(((~o)*255).astype('uint8')).resize((W,H),Image.BOX))>=128)|L
    return L,M
def fit(png,W,H,ref):
    g=np.array(Image.open(png+'.png').convert('L'))
    g=np.where(g>200,255,g)                       # clean the light grey paper
    x0,x1,y0,y1=bbox(g<128)
    rx0,rx1,ry0,ry1=bbox(ref)
    th=ry1-ry0                                     # same figure height as idle
    s=th/(y1-y0); nw=round((x1-x0)*s)
    if nw>W-2: s=(W-2)/(x1-x0); nw=W-2
    nh=round((y1-y0)*s)
    crop=Image.fromarray(g[y0:y1,x0:x1]).resize((nw,nh),Image.BOX)
    canvas=Image.new('L',(W,H),255)
    cx=(rx0+rx1)//2; px=min(max(cx-nw//2,0),W-nw); py=min(ry1,H)-nh
    canvas.paste(crop,(px,max(py,0)))
    a=np.array(canvas); L=a<T
    big=np.array(Image.fromarray(g).point(lambda v:255 if v>=128 else 0))
    # mask: inside of the outline, at full res, then shrunk the same way
    o=outside(np.where(g<128,0,255))
    mk=Image.fromarray(((~o[y0:y1,x0:x1])*255).astype("uint8")).resize((nw,nh),Image.BOX)
    mc=Image.new('L',(W,H),0); mc.paste(mk,(px,max(py,0)))
    M=(np.array(mc)>=128)|L
    return L,M
out=['// mood frames (v1.2): happy for every stage, hungry for teen/adult. Drawn new in the same line-art style',
     '// as limengdu/reTerminal_Sticky_Bunny (MIT). Generated by tools/gen_mood_frames.py.','#pragma once','#include "pet_frames.h"','']
prev=[]; total=0
already=('idle_hungry','child_idle_hungry','youth_active_signature','adult_active_signature')   # in pet_frames.h
for st,W,H,idle,union,moods in STAGES:
    ref,_=old_frame(idle,union,W,H)
    row=[]
    def tile(L,M):
        rgb=np.zeros((H,W,3),'uint8'); rgb[:]=(16,24,64); rgb[M]=255; rgb[L]=0
        return Image.fromarray(rgb).resize((W*3,H*3),Image.NEAREST)
    for mood,(kind,png) in zip(MOODS,moods):
        L,M=old_frame(png,union,W,H) if kind=='old' else fit(png,W,H,ref)
        tag='existing' if png in already else ('pack art' if kind=='old' else 'NEW')
        if png not in already:
            a1,a2=pack(L),pack(M); total+=len(a1)+len(a2)
            n=f'{st}_{mood}'; out.append(arr(n+'_ink',a1)); out.append(arr(n+'_mask',a2))
            out.append(f'const Sprite {st.upper()}_{mood.upper()} = {{{W}, {H}, {n}_ink, {n}_mask}};\n')
        row.append((f'{mood} ({tag})',tile(L,M)))
    prev.append((st,row))
out.append(f'#define MOOD_FRAMES_BYTES {total}')
open('mood_frames.h','w').write('\n'.join(out)+'\n')
# preview sheet
from PIL import ImageFont
f=ImageFont.load_default()
rows=[]
for st,row in prev:
    Wt=sum(i.width for _,i in row)+16*len(row)+90; Ht=max(i.height for _,i in row)+22
    im=Image.new('RGB',(Wt,Ht),(40,40,40)); d=ImageDraw.Draw(im); d.text((6,Ht//2),st.upper(),fill=(232,131,58),font=f); x=90
    for lab,i in row: im.paste(i,(x,0)); d.text((x+2,i.height+5),lab,fill=(220,220,220),font=f); x+=i.width+16
    rows.append(im)
Wt=max(r.width for r in rows); Ht=sum(r.height+10 for r in rows)
sheet=Image.new('RGB',(Wt,Ht),(40,40,40)); y=0
for r in rows: sheet.paste(r,(0,y)); y+=r.height+10
sheet.save('mood_preview.png'); print('bytes',total,sheet.size)
