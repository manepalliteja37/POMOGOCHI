#!/usr/bin/env python3
# gen_shop_art.py - builds shop_art.h for the v1.2 rewards shop (hats + scenes + hat anchors).
# Hats are hand-drawn pixel art (in art.py style, inline below), scenes are drawn with PIL, and the hat anchor
# for every Home rabbit frame is found from its mask: the first row (from the top) with one solid run at least
# MINRUN px wide = the top of the head (ears are thin runs). Run from the firmware folder:
#   python3 ../tools/gen_shop_art.py   (reads pet_frames.h + mood_frames.h, writes shop_art.h)
import re, sys, os, math, random
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from shop_art_src import *
from PIL import Image

def load(path):
    s = open(path).read()
    arrs = {m.group(1): bytes(int(x, 16) for x in re.findall(r'0x([0-9A-Fa-f]{2})', m.group(2)))
            for m in re.finditer(r'const uint8_t (\w+)\[\] PROGMEM = \{(.*?)\};', s, re.S)}
    spr = {}
    for m in re.finditer(r'const Sprite (\w+)\[\] = \{(.*?)\};', s, re.S):
        spr[m.group(1)] = [(int(a), int(b), i, mk) for a, b, i, mk in re.findall(r'\{(\d+), (\d+), (\w+), (\w+)\}', m.group(2))]
    for m in re.finditer(r'const Sprite (\w+) = \{(\d+), (\d+), (\w+), (\w+)\};', s):
        spr[m.group(1)] = (int(m.group(2)), int(m.group(3)), m.group(4), m.group(5))
    return arrs, spr
def bits(arr, w, h):
    rb = (w + 7) // 8
    return [[(arr[r * rb + c // 8] >> (7 - c % 8)) & 1 for c in range(w)] for r in range(h)]
MINRUN = {55: 18, 66: 18, 59: 18, 100: 24}
def anchor(w, h, mask):
    for r in range(h):
        c = 0
        while c < w:
            if mask[r][c]:
                s = c
                while c < w and mask[r][c]: c += 1
                if c - s >= MINRUN[w]: return (s + c - 1) // 2, r
            else: c += 1
    return w // 2, 0
def pack(rows, w):
    out = []
    for row in rows:
        for b in range(0, w, 8):
            v = 0
            for k in range(8):
                if b + k < w and row[b + k]: v |= 0x80 >> k
            out.append(v)
    return out
def carr(name, data):
    lines = [','.join('0x%02X' % x for x in data[i:i + 16]) for i in range(0, len(data), 16)]
    return 'const uint8_t %s[] PROGMEM = {\n  %s\n};\n' % (name, ',\n  '.join(lines))

fw = sys.argv[1] if len(sys.argv) > 1 else '.'
a1, s1 = load(os.path.join(fw, 'pet_frames.h')); a2, s2 = load(os.path.join(fw, 'mood_frames.h'))
A = {**a1, **a2}; S = {**s1, **s2}
out = ['// shop_art.h - v1.2 rewards shop art: 6 hats, 4 scenes, and where a hat sits on every Home frame.',
       '// Generated by tools/gen_shop_art.py (pixel art drawn for this project, CC0).', '#pragma once',
       '#include "pet_frames.h"', '#include "mood_frames.h"', '',
       'struct HatArt   { uint8_t w, h; const uint8_t *ink, *fa, *fb; uint16_t ca, cb; uint8_t cost, needStreak; const char* name; };',
       'struct SceneArt { const uint8_t* bits; uint16_t col; uint8_t top; uint8_t cost, needStreak; const char* name; };',
       'struct HatAnchor { const Sprite* s; int8_t ax, ay; };', '']
total = 0
for i, n in enumerate(HAT_ORDER):
    ca, cb, rows = HATS[n]; w = len(rows[0]); h = len(rows)
    assert all(len(r) == w for r in rows), n
    for pl, ch in (('ink', '#'), ('fa', 'o'), ('fb', 'x')):
        d = pack([[c == ch for c in r] for r in rows], w); total += len(d)
        out.append(carr('hat_%s_%s' % (n, pl), d))
for n in SCENE_ORDER:
    im = SCENES[n]()
    d = pack([[im.getpixel((x, y)) for x in range(128)] for y in range(24)], 128); total += len(d)
    out.append(carr('scene_%s' % n, d))
out.append('const HatArt HATS[] = {')
for i, n in enumerate(HAT_ORDER):
    ca, cb, rows = HATS[n]
    out.append('  {%d, %d, hat_%s_ink, hat_%s_fa, hat_%s_fb, 0x%04X, 0x%04X, %d, %d, "%s"},' %
               (len(rows[0]), len(rows), n, n, n, ca, cb, HAT_COST[i], HAT_NEED_STREAK[i], HAT_LABEL[i]))
out.append('};\nconst uint8_t N_HATS = %d;' % len(HAT_ORDER))
out.append('const SceneArt SCENES[] = {')
for i, n in enumerate(SCENE_ORDER):
    out.append('  {scene_%s, 0x%04X, %d, %d, %d, "%s"},' % (n, SCENE_COL[n], 1 if SCENE_TOP[n] else 0, SCENE_COST[i], SCENE_NEED_STREAK[i], SCENE_LABEL[i]))
out.append('};\nconst uint8_t N_SCENES = %d;' % len(SCENE_ORDER))
anc = []
for nm in ('BABY', 'KID', 'TEEN', 'ADULT'):
    for i, (w, h, ink, mk) in enumerate(S[nm]):
        ax, ay = anchor(w, h, bits(A[mk], w, h)); anc.append('  {&%s[%d], %d, %d},' % (nm, i, ax, ay))
for nm in ('BABY_CALM', 'BABY_HAPPY', 'BABY_LOVE', 'KID_CALM', 'KID_HAPPY', 'KID_LOVE', 'TEEN_SAD', 'TEEN_HAPPY', 'TEEN_LOVE', 'ADULT_SAD', 'ADULT_HAPPY', 'ADULT_LOVE'):
    w, h, ink, mk = S[nm]; ax, ay = anchor(w, h, bits(A[mk], w, h)); anc.append('  {&%s, %d, %d},' % (nm, ax, ay))
out.append('// top of the head on each frame (x, y inside the sprite); a hat sits centred on x with its bottom 3 px below y')
out.append('const HatAnchor HAT_ANCHORS[] PROGMEM = {\n' + '\n'.join(anc) + '\n};')
out.append('const uint8_t N_ANCHORS = %d;' % len(anc))
open(os.path.join(fw, 'shop_art.h'), 'w').write('\n'.join(out) + '\n')
print('shop_art.h: %d bytes of art, %d anchors' % (total, len(anc)))
